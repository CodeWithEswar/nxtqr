interface SeedChallengeSpec {
  id: string;
  slug: string;
  title: string;
  difficulty: ChallengeDifficulty;
  categories: ChallengeCategory[];
  estimatedMinutes: number;
  description: string;
  publicPrompt: string;
  concepts: string[];
  dau: number;
  reqPerDay: number;
  readWriteRatio: number;
  avgPayloadBytes: number;
  maxP95Ms: number;
  minAvailabilityPct: number;
  maxMonthlyCostUsd: number;
  requiredCapabilities: string[];
  requiredApiCapabilities: string[];
  requiredEntities: string[];
  reqTitleA: string;
  reqTitleB: string;
  nfrTarget: string;
  faultKind: ChallengeScenario["kind"];
  faultType: ChallengeScenario["faultType"];
}

function buildChallenge(spec: SeedChallengeSpec): SystemDesignChallenge {
  const avgRps = Math.max(10, Math.round((spec.dau * spec.reqPerDay) / 86400));
  const peakRps = avgRps * 3;
  const stressRps = Math.min(250000, peakRps * 2);

  const hints: HintDefinition[] = [
    {
      id: `${spec.id}_h1`,
      challengeId: spec.id,
      level: 1,
      phase: "requirements_discovery",
      title: "Clarify read vs write skew and SLA",
      content: `Ask about daily active users, read/write ratio (${spec.readWriteRatio}:1), and p95 latency expectations (${spec.maxP95Ms}ms) before choosing storage engines.`,
      prerequisiteHintIds: [],
    },
    {
      id: `${spec.id}_h2`,
      challengeId: spec.id,
      level: 2,
      phase: "capacity_estimation",
      title: "Bound peak QPS and replication footprint",
      content: `Estimate ~${avgRps} avg RPS and ~${peakRps} peak RPS before sizing stateless compute replicas or cache memory.`,
      prerequisiteHintIds: [`${spec.id}_h1`],
    },
    {
      id: `${spec.id}_h3`,
      challengeId: spec.id,
      level: 3,
      phase: "high_level_architecture",
      title: "Isolate hot read paths & avoid SPOFs",
      content: `Check whether ${spec.requiredCapabilities.join(" + ")} helps meet ${spec.maxP95Ms}ms p95 without leaving a single-replica bottleneck.`,
      prerequisiteHintIds: [`${spec.id}_h2`],
    },
    {
      id: `${spec.id}_h4`,
      challengeId: spec.id,
      level: 4,
      phase: "reliability_analysis",
      title: "Protect against dependency amplification",
      content: `Under ${spec.faultKind.replace(/_/g, " ")}, verify that retries are bounded and data stores span multiple AZs.`,
      prerequisiteHintIds: [`${spec.id}_h3`],
    },
    {
      id: `${spec.id}_h5`,
      challengeId: spec.id,
      level: 5,
      phase: "tradeoff_discussion",
      title: "Articulate what you intentionally sacrifice",
      content: `Explain why simpler primitives beat over-engineering when cost ceiling is $${spec.maxMonthlyCostUsd}/mo, and what breaks at 10x load.`,
      prerequisiteHintIds: [`${spec.id}_h4`],
    },
  ];

  return {
    version: 1,
    id: spec.id,
    slug: spec.slug,
    title: spec.title,
    description: spec.description,
    status: "published",
    difficulty: spec.difficulty,
    categories: spec.categories,
    estimatedMinutes: spec.estimatedMinutes,
    publicPrompt: spec.publicPrompt,
    concepts: spec.concepts,
    requirements: [
      {
        id: `${spec.id}_r1`,
        code: "FR-1",
        kind: "functional",
        title: spec.reqTitleA,
        description: `Core write/ingest operation for ${spec.title.replace("Design a ", "").replace("Design an ", "")}.`,
        discoveredByDefault: true,
        requiredComponentKinds: ["api_gateway", "app_server", "database"],
      },
      {
        id: `${spec.id}_r2`,
        code: "FR-2",
        kind: "functional",
        title: spec.reqTitleB,
        description: `Core query/delivery workflow supporting idempotent execution and clean error contracts.`,
        discoveredByDefault: false,
        requiredComponentKinds: ["app_server", "database"],
      },
      {
        id: `${spec.id}_r3`,
        code: "NFR-1",
        kind: "nonfunctional",
        title: `Latency & throughput envelope (${spec.maxP95Ms}ms p95)`,
        description: `Maintain p95 <= ${spec.maxP95Ms}ms and availability >= ${spec.minAvailabilityPct}% during peak traffic (~${peakRps} req/s).`,
        discoveredByDefault: false,
        metricTarget: `p95 <= ${spec.maxP95Ms}ms`,
        requiredComponentKinds: spec.requiredCapabilities.slice(0, 2),
        testScenarioId: `${spec.id}_sc_peak`,
      },
      {
        id: `${spec.id}_r4`,
        code: "NFR-2",
        kind: "nonfunctional",
        title: spec.nfrTarget,
        description: `Resilient operation during ${spec.faultKind.replace(/_/g, " ")} with bounded recovery and no unmitigated single point of failure.`,
        discoveredByDefault: false,
        metricTarget: `availability >= ${spec.minAvailabilityPct}%`,
        requiredComponentKinds: spec.requiredCapabilities,
        testScenarioId: `${spec.id}_sc_fault`,
      },
    ],
    discoveryRules: [
      {
        id: `${spec.id}_d1`,
        triggerKeywords: ["scale", "traffic", "dau", "qps", "rps", "latency", "read", "write", "throughput"],
        promptSample: "What is the expected DAU, peak RPS, read/write ratio, and latency SLA?",
        revealsRequirementIds: [`${spec.id}_r3`],
        interviewerResponse: `Expect ~${(spec.dau / 1_000_000).toFixed(spec.dau >= 1_000_000 ? 1 : 2)}M DAU, ${spec.readWriteRatio}:1 read/write ratio, peak ~${peakRps.toLocaleString()} req/s, and strict p95 <= ${spec.maxP95Ms}ms.`,
      },
      {
        id: `${spec.id}_d2`,
        triggerKeywords: ["core", "feature", "scope", "retention", "query", "deliver", "api", "workflow"],
        promptSample: "Which secondary workflows, data retention windows, and API semantics are in scope?",
        revealsRequirementIds: [`${spec.id}_r2`],
        interviewerResponse: `${spec.reqTitleB} is required in v1 with idempotent mutations, authenticated API boundaries, and 365-day baseline retention.`,
      },
      {
        id: `${spec.id}_d3`,
        triggerKeywords: ["failure", "availability", "region", "consistency", "durability", "security", "outage", "cost"],
        promptSample: "What are the availability, consistency, failure tolerance, and budget expectations?",
        revealsRequirementIds: [`${spec.id}_r4`],
        interviewerResponse: `Target ${spec.minAvailabilityPct}% availability under single-node or AZ faults, keep monthly infra under $${spec.maxMonthlyCostUsd}, and uphold: ${spec.nfrTarget}.`,
      },
    ],
    constraints: [
      {
        id: `${spec.id}_c_p95`,
        label: `Peak p95 latency <= ${spec.maxP95Ms} ms`,
        metric: "max_p95_ms",
        operator: "lte",
        threshold: spec.maxP95Ms,
        unit: "ms",
      },
      {
        id: `${spec.id}_c_avail`,
        label: `Availability >= ${spec.minAvailabilityPct}%`,
        metric: "min_availability_pct",
        operator: "gte",
        threshold: spec.minAvailabilityPct,
        unit: "%",
      },
      {
        id: `${spec.id}_c_spof`,
        label: "Zero unmitigated critical SPOFs",
        metric: "max_critical_spofs",
        operator: "lte",
        threshold: 0,
        unit: "SPOFs",
      },
      {
        id: `${spec.id}_c_cost`,
        label: `Monthly infrastructure <= $${spec.maxMonthlyCostUsd}`,
        metric: "max_monthly_cost_usd",
        operator: "lte",
        threshold: spec.maxMonthlyCostUsd,
        unit: "USD",
      },
    ],
    referenceWorkload: {
      dailyActiveUsers: spec.dau,
      requestsPerUserPerDay: spec.reqPerDay,
      peakMultiplier: 3,
      readWriteRatio: spec.readWriteRatio,
      avgPayloadBytes: spec.avgPayloadBytes,
      retentionDays: 365,
      replicationFactor: 3,
    },
    scenarios: [
      {
        id: `${spec.id}_sc_normal`,
        label: "Normal Baseline Traffic",
        kind: "normal_traffic",
        workloadRps: Math.max(50, Math.min(8000, avgRps)),
        faultType: "none",
        latencyInflationMs: 0,
      },
      {
        id: `${spec.id}_sc_peak`,
        label: "Peak Traffic Surge",
        kind: "peak_traffic",
        workloadRps: Math.max(150, Math.min(20000, peakRps)),
        faultType: "none",
        latencyInflationMs: 5,
      },
      {
        id: `${spec.id}_sc_fault`,
        label: `Failure / Stress (${spec.faultKind.replace(/_/g, " ")})`,
        kind: spec.faultKind,
        workloadRps: Math.max(200, Math.min(25000, stressRps)),
        faultType: spec.faultType,
        latencyInflationMs: 18,
      },
    ],
    rubricId: STANDARD_PRACTICE_RUBRIC.id,
    hints,
    commonMistakes: [
      "Jumping to microservices or Kubernetes without validating bottlenecks or latency budgets first.",
      "Ignoring single points of failure on stateful primary databases or uncached hot keys.",
      "Using unbounded retries that trigger retry storms during partial dependency slowdowns.",
    ],
    alternativeApproaches: [
      "Modular monolith + managed replicated DB + cache-aside for low operational overhead.",
      "Horizontally sharded stateless compute + partitioned storage + async queue decoupling for heavy write bursts.",
    ],
    learningObjectives: [
      `Discover quantified throughput, latency (${spec.maxP95Ms}ms), and availability (${spec.minAvailabilityPct}%) targets before drawing nodes.`,
      `Design right-sized ${spec.concepts.slice(0, 2).join(" and ")} mechanisms justified by simulation evidence.`,
    ],
    evaluatorOnly: {
      expectedPeakRpsMin: Math.max(1, Math.round(peakRps * 0.15)),
      expectedPeakRpsMax: Math.max(100, Math.round(peakRps * 12)),
      requiredComponentCapabilities: spec.requiredCapabilities,
      requiredApiCapabilities: spec.requiredApiCapabilities,
      requiredEntityConcepts: spec.requiredEntities,
    },
  };
}

